type ProjectSummary struct {
	ID        string    `json:"id"`
	Name      string    `json:"name"`
	Thumbnail string    `json:"thumbnail"`
	Version   int64     `json:"version"`
	CreatedAt time.Time `json:"createdAt"`
	UpdatedAt time.Time `json:"updatedAt"`
	// Kind is the kind of building (data.kind, "" when it's missing or not text);
	// only set by ListProjects, so the list can group buildings without loading their data.
	Kind string `json:"kind,omitempty"`
}

type Project struct {
	ProjectSummary
	Data json.RawMessage `json:"data"`
}

// ProjectUpdate holds the fields to change; nil or empty fields are left alone.
type ProjectUpdate struct {
	Name      *string
	Data      json.RawMessage
	Thumbnail *string
}

func newID() string {
	b := make([]byte, 10)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return strings.ToLower(base32.StdEncoding.WithPadding(base32.NoPadding).EncodeToString(b))
}

func scanProject(row scanner) (Project, error) {
	var p Project
	var data string
	var created, updated int64
	err := row.Scan(&p.ID, &p.Name, &p.Thumbnail, &p.Version, &created, &updated, &data)
	if errors.Is(err, sql.ErrNoRows) {
		return Project{}, ErrNotFound
	}
	if err != nil {
		return Project{}, err
	}
	p.CreatedAt, p.UpdatedAt = time.UnixMilli(created), time.UnixMilli(updated)
	p.Data = json.RawMessage(data)
	return p, nil
}

const projectCols = "id, name, thumbnail, version, created_at, updated_at, data"

func (s *Store) CreateProject(ctx context.Context, userID int64, name string, data json.RawMessage) (Project, error) {
	return s.insertProject(ctx, userID, name, data, "")
}

func (s *Store) insertProject(ctx context.Context, userID int64, name string, data json.RawMessage, thumbnail string) (Project, error) {
	id, now := newID(), s.ms()
	_, err := s.exec(ctx, `INSERT INTO projects (id, user_id, name, data, thumbnail, version, created_at, updated_at) VALUES (?, ?, ?, ?, ?, 1, ?, ?)`,
		id, userID, name, string(data), thumbnail, now, now)
	if err != nil {
		return Project{}, err
	}
	return s.GetProject(ctx, userID, id)
}

// ListProjects returns a user's projects, the last edited first.
func (s *Store) ListProjects(ctx context.Context, userID int64) ([]ProjectSummary, error) {
	// data is always a JSON object (the API checks it), stored as text in both databases.
	kind := `CASE WHEN json_type(data, '$.kind') = 'text' THEN json_extract(data, '$.kind') ELSE '' END`
	if s.dialect == postgres {
		kind = `CASE WHEN jsonb_typeof(data::jsonb -> 'kind') = 'string' THEN data::jsonb ->> 'kind' ELSE '' END`
	}
	rows, err := s.query(ctx, `SELECT id, name, thumbnail, version, created_at, updated_at, `+kind+` FROM projects WHERE user_id = ? ORDER BY updated_at DESC, id`, userID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	list := []ProjectSummary{}
	for rows.Next() {
		var p ProjectSummary
		var created, updated int64
		if err := rows.Scan(&p.ID, &p.Name, &p.Thumbnail, &p.Version, &created, &updated, &p.Kind); err != nil {
			return nil, err
		}
		p.CreatedAt, p.UpdatedAt = time.UnixMilli(created), time.UnixMilli(updated)
		list = append(list, p)
	}
	return list, rows.Err()
}

// GetProject returns a project if it belongs to userID, else ErrNotFound.
func (s *Store) GetProject(ctx context.Context, userID int64, id string) (Project, error) {
	return scanProject(s.queryRow(ctx, `SELECT `+projectCols+` FROM projects WHERE id = ? AND user_id = ?`, id, userID))
}

// UpdateProject changes a project. If ifVersion is not 0 and the project is at
// another version, nothing changes and the current project is returned with ErrConflict.
func (s *Store) UpdateProject(ctx context.Context, userID int64, id string, u ProjectUpdate, ifVersion int64) (Project, error) {
	tx, err := s.begin(ctx)
	if err != nil {
		return Project{}, err
	}
	defer tx.Rollback()
	sel := `SELECT ` + projectCols + ` FROM projects WHERE id = ? AND user_id = ?`
	if s.dialect == postgres {
		sel += " FOR UPDATE" // two saves at once: the second waits, then sees the new version
	}
	cur, err := scanProject(tx.queryRow(ctx, sel, id, userID))
	if err != nil {
		return Project{}, err
	}
	if ifVersion != 0 && ifVersion != cur.Version {
		return cur, ErrConflict
	}
	if u.Name != nil {
		cur.Name = *u.Name
	}
	if len(u.Data) > 0 {
		cur.Data = u.Data
	}
	if u.Thumbnail != nil {
		cur.Thumbnail = *u.Thumbnail
	}
	cur.Version++
	now := s.ms()
	cur.UpdatedAt = time.UnixMilli(now)
	if _, err := tx.exec(ctx, `UPDATE projects SET name = ?, data = ?, thumbnail = ?, version = ?, updated_at = ? WHERE id = ?`,
		cur.Name, string(cur.Data), cur.Thumbnail, cur.Version, now, id); err != nil {
		return Project{}, err
	}
	return cur, tx.Commit()
}

func (s *Store) DeleteProject(ctx context.Context, userID int64, id string) error {
	res, err := s.exec(ctx, `DELETE FROM projects WHERE id = ? AND user_id = ?`, id, userID)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n != 1 {
		return ErrNotFound
	}
	return nil
}

// DuplicateProject copies a project (data and thumbnail) under a new name.
func (s *Store) DuplicateProject(ctx context.Context, userID int64, id, name string) (Project, error) {
	src, err := s.GetProject(ctx, userID, id)
	if err != nil {
		return Project{}, err
	}
	return s.insertProject(ctx, userID, name, src.Data, src.Thumbnail)
}
