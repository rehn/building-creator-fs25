var (
	ErrNotFound   = errors.New("not found")
	ErrEmailTaken = errors.New("email already registered")
	ErrConflict   = errors.New("conflict")
)

type dialect int

const (
	sqlite dialect = iota
	postgres
)

type Store struct {
	db      *sql.DB
	dialect dialect
	// Now is the clock; tests replace it.
	Now func() time.Time
}

