// IsPostgresURL reports whether dsn is a Postgres connection URL (postgres:// or postgresql://).
func IsPostgresURL(dsn string) bool {
	l := strings.ToLower(strings.TrimSpace(dsn))
	return strings.HasPrefix(l, "postgres://") || strings.HasPrefix(l, "postgresql://")
}

// Open opens (and creates the tables in, if needed) the database: a Postgres URL
// (postgres://user:pass@host:5432/db) or the path of a SQLite file. Use ":memory:" for tests.
func Open(dsn string) (*Store, error) {
	if IsPostgresURL(dsn) {
		return openPostgres(dsn)
	}
	return openSQLite(dsn)
}

func openPostgres(url string) (*Store, error) {
	db, err := sql.Open("pgx", url)
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(10)
	db.SetConnMaxIdleTime(5 * time.Minute)
	s := &Store{db: db, dialect: postgres, Now: time.Now}
	// Several API pods may start at once: the advisory lock makes them create the tables one at a time.
	err = s.inTx(context.Background(), func(tx *txx) error {
		if _, err := tx.exec(context.Background(), `SELECT pg_advisory_xact_lock(7340211)`); err != nil {
			return err
		}
		if err := execAll(context.Background(), tx.Tx, schemaPostgres); err != nil {
			return err
		}
		_, err := tx.exec(context.Background(), `ALTER TABLE assets ADD COLUMN IF NOT EXISTS shared BOOLEAN NOT NULL DEFAULT FALSE`)
		return err
	})
	if err != nil {
		db.Close()
		return nil, fmt.Errorf("creating schema: %w", err)
	}
	return s, nil
}

type execer interface {
	ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error)
}

// execAll runs the ;-separated statements in script one by one.
func execAll(ctx context.Context, db execer, script string) error {
	for _, stmt := range strings.Split(script, ";") {
		if strings.TrimSpace(stmt) == "" {
			continue
		}
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			return err
		}
	}
	return nil
}

func openSQLite(path string) (*Store, error) {
	dsn := "file:" + path + "?_pragma=foreign_keys(1)&_pragma=busy_timeout(5000)"
	if path != ":memory:" {
		dsn += "&_pragma=journal_mode(WAL)"
	}
	db, err := sql.Open("sqlite", dsn)
	if err != nil {
		return nil, err
	}
	// One connection: SQLite allows one writer anyway, and ":memory:" needs a single connection.
	db.SetMaxOpenConns(1)
	if err := execAll(context.Background(), db, schemaSQLite); err != nil {
		db.Close()
		return nil, fmt.Errorf("creating schema: %w", err)
	}
	if err := addColumnSQLite(db, "assets", "shared", "INTEGER NOT NULL DEFAULT 0"); err != nil {
		db.Close()
		return nil, fmt.Errorf("updating schema: %w", err)
	}
	return &Store{db: db, dialect: sqlite, Now: time.Now}, nil
}

// addColumnSQLite adds a column to a table that doesn't have it yet (SQLite has no ADD COLUMN IF NOT EXISTS).
func addColumnSQLite(db *sql.DB, table, column, def string) error {
	var n int
	if err := db.QueryRow(`SELECT count(*) FROM pragma_table_info(?) WHERE name = ?`, table, column).Scan(&n); err != nil || n > 0 {
		return err
	}
	_, err := db.Exec(`ALTER TABLE ` + table + ` ADD COLUMN ` + column + ` ` + def)
	return err
}

// rebind turns ? placeholders (outside quoted strings) into $1, $2, ... for Postgres.
func rebind(d dialect, q string) string {
	if d != postgres {
		return q
	}
	var b strings.Builder
	n, quoted := 0, false
	for _, r := range q {
		switch {
		case r == '\'':
			quoted = !quoted
			b.WriteRune(r)
		case r == '?' && !quoted:
			n++
			fmt.Fprintf(&b, "$%d", n)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func (s *Store) exec(ctx context.Context, q string, args ...any) (sql.Result, error) {
	return s.db.ExecContext(ctx, rebind(s.dialect, q), args...)
}
func (s *Store) queryRow(ctx context.Context, q string, args ...any) *sql.Row {
	return s.db.QueryRowContext(ctx, rebind(s.dialect, q), args...)
}
func (s *Store) query(ctx context.Context, q string, args ...any) (*sql.Rows, error) {
	return s.db.QueryContext(ctx, rebind(s.dialect, q), args...)
}

// txx is a transaction that rewrites placeholders like Store does.
type txx struct {
	*sql.Tx
	dialect dialect
}

func (t *txx) exec(ctx context.Context, q string, args ...any) (sql.Result, error) {
	return t.ExecContext(ctx, rebind(t.dialect, q), args...)
}
func (t *txx) queryRow(ctx context.Context, q string, args ...any) *sql.Row {
	return t.QueryRowContext(ctx, rebind(t.dialect, q), args...)
}

func (s *Store) begin(ctx context.Context) (*txx, error) {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return nil, err
	}
	return &txx{Tx: tx, dialect: s.dialect}, nil
}

// inTx runs fn in a transaction and commits it if fn returns nil.
func (s *Store) inTx(ctx context.Context, fn func(tx *txx) error) error {
	tx, err := s.begin(ctx)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if err := fn(tx); err != nil {
		return err
	}
	return tx.Commit()
}

func (s *Store) Close() error { return s.db.Close() }

func (s *Store) ms() int64 { return s.Now().UnixMilli() }

// uniqueViolation reports whether err is a unique constraint violation, and on what
// (the SQLite message names the column, Postgres the constraint or index).
func uniqueViolation(err error) (what string, ok bool) {
	var pg *pgconn.PgError
	if errors.As(err, &pg) && pg.Code == "23505" {
		return pg.ConstraintName, true
	}
	if err != nil && strings.Contains(err.Error(), "UNIQUE constraint failed") {
		return err.Error(), true
	}
	return "", false
}

func isUnique(err error) bool { _, ok := uniqueViolation(err); return ok }

func nullStr(v string) sql.NullString { return sql.NullString{String: v, Valid: v != ""} }

/* ---------- Users ---------- */

type User struct {
	ID          int64     `json:"id"`
	Email       string    `json:"email"`
	Name        string    `json:"name"`
	IsAdmin     bool      `json:"isAdmin"`
	HasPassword bool      `json:"hasPassword"`
	HasGoogle   bool      `json:"hasGoogle"`
	CreatedAt   time.Time `json:"createdAt"`
}

type NewUser struct {
	Email        string
	Name         string
	PasswordHash string
	GoogleSub    string
	IsAdmin      bool
}

const userCols = "id, email, name, password_hash, google_sub, is_admin, created_at"

type scanner interface{ Scan(dest ...any) error }

func scanUser(row scanner) (User, string, error) {
	var u User
	var hash, sub sql.NullString
	var created int64
	err := row.Scan(&u.ID, &u.Email, &u.Name, &hash, &sub, &u.IsAdmin, &created)
	if errors.Is(err, sql.ErrNoRows) {
		return User{}, "", ErrNotFound
	}
	if err != nil {
		return User{}, "", err
	}
	u.HasPassword = hash.Valid && hash.String != ""
	u.HasGoogle = sub.Valid && sub.String != ""
	u.CreatedAt = time.UnixMilli(created)
	return u, hash.String, nil
}

// CreateUser adds a user. If inviteID is not 0, the invite is marked used in
// the same transaction, and the user is not created if the invite is gone.
func (s *Store) CreateUser(ctx context.Context, nu NewUser, inviteID int64) (User, error) {
	tx, err := s.begin(ctx)
	if err != nil {
		return User{}, err
	}
	defer tx.Rollback()
	now := s.ms()
	if inviteID != 0 {
		res, err := tx.exec(ctx, `UPDATE invites SET used_at = ? WHERE id = ? AND used_at IS NULL AND expires_at > ?`, now, inviteID, now)
		if err != nil {
			return User{}, err
		}
		if n, _ := res.RowsAffected(); n != 1 {
			return User{}, ErrNotFound
		}
	}
	var id int64
	err = tx.queryRow(ctx, `INSERT INTO users (email, name, password_hash, google_sub, is_admin, created_at) VALUES (?, ?, ?, ?, ?, ?) RETURNING id`,
		nu.Email, nu.Name, nullStr(nu.PasswordHash), nullStr(nu.GoogleSub), nu.IsAdmin, now).Scan(&id)
	if what, ok := uniqueViolation(err); ok {
		if strings.Contains(what, "email") {
			return User{}, ErrEmailTaken
		}
		return User{}, ErrConflict
	}
	if err != nil {
		return User{}, err
	}
	u, _, err := scanUser(tx.queryRow(ctx, `SELECT `+userCols+` FROM users WHERE id = ?`, id))
	if err != nil {
		return User{}, err
	}
	return u, tx.Commit()
}

// UserByEmail returns the user and their password hash ("" if they have none).
func (s *Store) UserByEmail(ctx context.Context, email string) (User, string, error) {
	return scanUser(s.queryRow(ctx, `SELECT `+userCols+` FROM users WHERE lower(email) = lower(?)`, email))
}

func (s *Store) UserByID(ctx context.Context, id int64) (User, error) {
	u, _, err := scanUser(s.queryRow(ctx, `SELECT `+userCols+` FROM users WHERE id = ?`, id))
	return u, err
}

func (s *Store) UserByGoogleSub(ctx context.Context, sub string) (User, error) {
	u, _, err := scanUser(s.queryRow(ctx, `SELECT `+userCols+` FROM users WHERE google_sub = ?`, sub))
	return u, err
}

func (s *Store) LinkGoogle(ctx context.Context, userID int64, sub string) error {
	res, err := s.exec(ctx, `UPDATE users SET google_sub = ? WHERE id = ?`, sub, userID)
	if isUnique(err) {
		return ErrConflict
	}
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n != 1 {
		return ErrNotFound
	}
	return nil
}

func (s *Store) CountUsers(ctx context.Context) (int, error) {
	var n int
	err := s.queryRow(ctx, `SELECT COUNT(*) FROM users`).Scan(&n)
	return n, err
}

/* ---------- Sessions ---------- */

func (s *Store) CreateSession(ctx context.Context, userID int64, tokenHash string, expires time.Time) error {
	_, err := s.exec(ctx, `INSERT INTO sessions (token_hash, user_id, expires_at, created_at) VALUES (?, ?, ?, ?)`,
		tokenHash, userID, expires.UnixMilli(), s.ms())
	return err
}

// SessionUser returns the user of a session that hasn't expired.
func (s *Store) SessionUser(ctx context.Context, tokenHash string) (User, error) {
	u, _, err := scanUser(s.queryRow(ctx, `SELECT u.id, u.email, u.name, u.password_hash, u.google_sub, u.is_admin, u.created_at
		FROM sessions s JOIN users u ON u.id = s.user_id WHERE s.token_hash = ? AND s.expires_at > ?`, tokenHash, s.ms()))
	return u, err
}

func (s *Store) DeleteSession(ctx context.Context, tokenHash string) error {
	_, err := s.exec(ctx, `DELETE FROM sessions WHERE token_hash = ?`, tokenHash)
	return err
}

func (s *Store) DeleteExpiredSessions(ctx context.Context) (int64, error) {
	res, err := s.exec(ctx, `DELETE FROM sessions WHERE expires_at <= ?`, s.ms())
	if err != nil {
		return 0, err
	}
	return res.RowsAffected()
}

/* ---------- Invites ---------- */

type Invite struct {
	ID        int64      `json:"id"`
	Email     string     `json:"email"`
	CreatedAt time.Time  `json:"createdAt"`
	ExpiresAt time.Time  `json:"expiresAt"`
	UsedAt    *time.Time `json:"usedAt,omitempty"`
}

const inviteCols = "id, email, created_at, expires_at, used_at"

func scanInvite(row scanner) (Invite, error) {
	var inv Invite
	var created, expires int64
	var used sql.NullInt64
	err := row.Scan(&inv.ID, &inv.Email, &created, &expires, &used)
	if errors.Is(err, sql.ErrNoRows) {
		return Invite{}, ErrNotFound
	}
	if err != nil {
		return Invite{}, err
	}
	inv.CreatedAt, inv.ExpiresAt = time.UnixMilli(created), time.UnixMilli(expires)
	if used.Valid {
		t := time.UnixMilli(used.Int64)
		inv.UsedAt = &t
	}
	return inv, nil
}

// CreateInvite adds an invite for email, replacing any open invite for it.
func (s *Store) CreateInvite(ctx context.Context, email, tokenHash string, createdBy int64, expires time.Time) (Invite, error) {
	tx, err := s.begin(ctx)
	if err != nil {
		return Invite{}, err
	}
	defer tx.Rollback()
	if _, err := tx.exec(ctx, `DELETE FROM invites WHERE lower(email) = lower(?) AND used_at IS NULL`, email); err != nil {
		return Invite{}, err
	}
	var id int64
	err = tx.queryRow(ctx, `INSERT INTO invites (email, token_hash, created_by, created_at, expires_at) VALUES (?, ?, ?, ?, ?) RETURNING id`,
		email, tokenHash, createdBy, s.ms(), expires.UnixMilli()).Scan(&id)
	if err != nil {
		return Invite{}, err
	}
	inv, err := scanInvite(tx.queryRow(ctx, `SELECT `+inviteCols+` FROM invites WHERE id = ?`, id))
	if err != nil {
		return Invite{}, err
	}
	return inv, tx.Commit()
}

// InviteByToken returns an unused, unexpired invite.
func (s *Store) InviteByToken(ctx context.Context, tokenHash string) (Invite, error) {
	return scanInvite(s.queryRow(ctx, `SELECT `+inviteCols+` FROM invites WHERE token_hash = ? AND used_at IS NULL AND expires_at > ?`, tokenHash, s.ms()))
}

// OpenInviteForEmail returns the newest unused, unexpired invite for email.
func (s *Store) OpenInviteForEmail(ctx context.Context, email string) (Invite, error) {
	return scanInvite(s.queryRow(ctx, `SELECT `+inviteCols+` FROM invites WHERE lower(email) = lower(?) AND used_at IS NULL AND expires_at > ? ORDER BY created_at DESC LIMIT 1`, email, s.ms()))
}

func (s *Store) ListInvites(ctx context.Context) ([]Invite, error) {
	rows, err := s.query(ctx, `SELECT `+inviteCols+` FROM invites ORDER BY created_at DESC, id DESC`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	list := []Invite{}
	for rows.Next() {
		inv, err := scanInvite(rows)
		if err != nil {
			return nil, err
		}
		list = append(list, inv)
	}
	return list, rows.Err()
}

func (s *Store) DeleteInvite(ctx context.Context, id int64) error {
	res, err := s.exec(ctx, `DELETE FROM invites WHERE id = ?`, id)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n != 1 {
		return ErrNotFound
	}
	return nil
}

